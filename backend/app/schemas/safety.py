"""Pydantic schemas for Safety Report CRUD and Investigation Lifecycles.

Task: M4-07 Safety Report Handling
PRD References: Section 4.8 (Women's Safety & Unsafe Locations), Section 7.5 (Safety Reporting)
"""
from datetime import datetime
from typing import List, Optional
from uuid import UUID
from pydantic import BaseModel, ConfigDict, Field, field_validator

from app.schemas.complaint import (
    ComplaintPriority,
    ComplaintStatus,
    ComplaintUpdateItem,
)

# Canonical safety categories from PRD §4.8, §4.2, and existing schema taxonomy
ALLOWED_SAFETY_CATEGORIES = {
    "Lighting issue",
    "Pedestrian accessibility issue",
    "Public transport infrastructure issue",
    "Repeated citizen concern",
    "Unverified safety concern",
    "Poor Lighting",
    "Deserted Bus Stop",
    "Dark Alley",
    "Unsafe Crossing",
    "Non-functional streetlights",
    "Poorly lit pedestrian routes",
    "Damaged or obstructed footpaths",
    "Unsafe or poorly maintained bus stops",
    "Broken public facilities",
    "Location feels unsafe",
}


class SafetyReportCreate(BaseModel):
    """Schema for a citizen submitting a public infrastructure safety concern.

    Privileged fields (citizen_id, safety_related, status, priority, severity,
    department_id, report_count) are strictly forbidden to prevent citizen tampering.
    """
    model_config = ConfigDict(extra="forbid")

    title: Optional[str] = Field(
        None,
        min_length=3,
        max_length=200,
        description="Optional brief summary of the safety issue (generated by AI if omitted)",
    )
    description: str = Field(
        ...,
        min_length=5,
        max_length=2000,
        description="Detailed description of the unsafe infrastructure condition",
    )
    latitude: float = Field(
        ...,
        ge=-90.0,
        le=90.0,
        description="Geographic latitude coordinate (-90 to +90)",
    )
    longitude: float = Field(
        ...,
        ge=-180.0,
        le=180.0,
        description="Geographic longitude coordinate (-180 to +180)",
    )
    safety_category: str = Field(
        ...,
        min_length=2,
        max_length=100,
        description="Type of safety concern (e.g. Poor Lighting, Deserted Bus Stop, Lighting issue)",
    )
    image_url: Optional[str] = Field(
        None,
        description="Namespaced storage path of uploaded photograph in complaint-images bucket",
    )

    @field_validator("description")
    @classmethod
    def validate_description_not_whitespace(cls, v: str) -> str:
        clean = v.strip()
        if not clean or len(clean) < 5:
            raise ValueError("Description must contain at least 5 non-whitespace characters.")
        return clean

    @field_validator("safety_category")
    @classmethod
    def validate_safety_category(cls, v: str) -> str:
        clean = v.strip()
        lookup = {cat.lower(): cat for cat in ALLOWED_SAFETY_CATEGORIES}
        if clean.lower() not in lookup:
            allowed_str = ", ".join(sorted(ALLOWED_SAFETY_CATEGORIES))
            raise ValueError(
                f"Invalid safety category '{clean}'. Allowed categories are: {allowed_str}"
            )
        return lookup[clean.lower()]


class SafetyInvestigationUpdate(BaseModel):
    """Schema for designated safety officers updating safety investigation status."""
    model_config = ConfigDict(extra="forbid")

    status: ComplaintStatus = Field(
        ...,
        description="New lifecycle status for the safety investigation",
    )
    remarks: str = Field(
        ...,
        min_length=3,
        max_length=1000,
        description="Official investigation remarks explaining the update or triage findings",
    )
    department_id: Optional[UUID] = Field(
        None,
        description="Department assignment or transfer target",
    )
    priority: Optional[ComplaintPriority] = Field(
        None,
        description="Updated municipal priority rating",
    )
    severity: Optional[int] = Field(
        None,
        ge=1,
        le=10,
        description="Updated physical hazard severity rating (1 to 10)",
    )

    @field_validator("remarks")
    @classmethod
    def validate_remarks_not_whitespace(cls, v: str) -> str:
        clean = v.strip()
        if not clean or len(clean) < 3:
            raise ValueError("Remarks must contain at least 3 non-whitespace characters.")
        return clean


class SafetyReportResponse(BaseModel):
    """Standard representation of a safety infrastructure report."""
    model_config = ConfigDict(from_attributes=True)

    id: UUID
    citizen_id: UUID
    citizen_name: Optional[str] = None
    title: str
    description: str
    latitude: float
    longitude: float
    category: str = "Unsafe public infrastructure"
    issue_type: str = "Safety Concern"
    department_id: Optional[UUID] = None
    department_name: Optional[str] = None
    severity: int = 5
    priority: ComplaintPriority = "Medium"
    status: ComplaintStatus = "Submitted"
    master_incident_id: Optional[UUID] = None
    report_count: int = 1
    safety_related: bool = True
    safety_category: Optional[str] = None
    image_url: Optional[str] = None
    image_signed_url: Optional[str] = None
    ai_summary: Optional[str] = None
    created_at: datetime
    updated_at: datetime


class SafetyReportDetailResponse(SafetyReportResponse):
    """Detailed view of a safety report including its chronological investigation history."""
    updates: List[ComplaintUpdateItem] = []
